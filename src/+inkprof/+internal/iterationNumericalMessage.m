function message=iterationNumericalMessage(c1,grid,c1File,gridFile)
alerts=join(string(c1.grossFailureAlerts),', ');
if ~c1.allNegativeControlsDetected,alerts=alerts+"; damaged-profile controls were not all detected";end
message="The ICC candidate was built, but its numerical checks require review."+newline+ ...
 "Check: "+alerts+newline+ ...
 sprintf('Maximum RGB-Lab-RGB-Lab roundtrip difference: %.3f Delta E00 (stop limit: 10).',grid.roundtripDeltaE00.max)+newline+ ...
 "The candidate has not been activated. Saved measurements and the previous profile are retained."+newline+ ...
 "Review these reports before retrying:"+newline+string(c1File)+newline+string(gridFile);
end
